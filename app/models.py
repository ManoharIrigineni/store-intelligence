from pydantic import BaseModel, Field
from typing import Optional, Dict, Any
from datetime import datetime

class EventMetadata(BaseModel):
    queue_depth: Optional[int] = None
    sku_zone: Optional[str] = None
    session_seq: int

class StoreEvent(BaseModel):
    event_id: str = Field(..., description="Globally unique UUIDv4 generated by pipeline")
    store_id: str = Field(..., description="Target store identifier from layout")
    camera_id: str = Field(..., description="Camera identifier supplying footage stream")
    visitor_id: str = Field(..., description="Unique persistent session tracking token")
    event_type: str = Field(..., description="Type of event (ENTRY, EXIT, ZONE_ENTER, etc.)")
    timestamp: datetime = Field(..., description="ISO-8601 UTC timestamp")
    zone_id: Optional[str] = None
    dwell_ms: int = 0
    is_staff: bool = False
    confidence: float
    metadata: EventMetadata
